from datetime import datetime
from typing import Protocol, TypeVar
from uuid import UUID

from ..models.records import Agent, Policy, PolicyVersion, Record
from .policies.lifecycle import PolicyStatus

T = TypeVar("T", bound=Record)


class RecordRepository(Protocol[T]):
    def add(self, record: T) -> T: ...
    def get(self, record_id: UUID) -> T | None: ...


class MutableRecordRepository(RecordRepository[T], Protocol[T]):
    def update(self, record: T) -> T: ...


class AgentConflict(ValueError):
    pass


class AgentRepository(MutableRecordRepository[Agent], Protocol):
    def get_for_update(self, agent_id: UUID) -> Agent | None: ...
    def list_owned(self, owner_id: UUID) -> list[Agent]: ...
    def get_owned(self, owner_id: UUID, agent_id: UUID, *, for_update: bool = False) -> Agent | None: ...


class PolicyRepository(Protocol):
    def add_policy(self, policy: Policy) -> Policy: ...
    def add_version(self, version: PolicyVersion) -> PolicyVersion: ...
    def list_owned(self, owner_id: UUID) -> list[Policy]: ...
    def get_owned(self, owner_id: UUID, policy_id: UUID, *, for_update: bool = False) -> Policy | None: ...
    def versions(self, policy_id: UUID) -> list[PolicyVersion]: ...
    def transition(self, version_id: UUID, target: PolicyStatus, at: datetime) -> PolicyVersion: ...
